#include <stdio.h>

int main() {
	//宣告三個二維陣列
    int A[2][4];	//宣告2橫列、4直行的表格A
    int B[4][5];	//宣告4橫列、5直行的表格B
    int C[2][5]={0};	//宣告2橫列、5直行的結果表格C，並把全部10格設為0
    int i,j,k;    //宣告迴圈要用的計數器變數：i表橫列(row)、j表直行(column)、k表A往右走、B往下走的同步計數器（共4格）

    //讀取使用者輸入的矩陣A
    printf("請輸入矩陣 A 的數值 (2x4，共 8 個整數)：\n");
    for (i = 0; i < 2; i++) {    //外層：控制橫列，從第0列跑到第1列（共2列）
        for (j = 0; j < 4; j++)    //內層：控制直行，從第0行跑到第3行（共4行）
    	    scanf("%d", &A[i][j]);    //讀取一整數，放進A表格的第i列、第j行
 	}

    //讀取使用者輸入的矩陣B
    printf("請輸入矩陣 B 的數值 (4x5，共 20 個整數)：\n");
    for (i = 0; i < 4; i++) {    //外層：控制橫列，從第0列跑到第3列（共4列）
        for (j = 0; j < 5; j++)    //內層：控制直行，從第0行跑到第4行（共5行）
            scanf("%d", &B[i][j]);    //讀取一整數，放進B表格的第i列、第j行
	} 

 	//計算：矩陣相乘（三層迴圈）
	for (i = 0; i < 2; i++) {    //第一層i：鎖定現在要算結果C的「第i橫列」（0或1）
    	for (j = 0; j < 5; j++) {    //第二層j：鎖定現在要算結果C的「第j直行」（0到4）
    	
    		//鎖定C[i][j]後，開始把「A的第i橫列」與「B的第j直行」兩兩相乘並累加
    		for (k = 0; k < 4; k++)    //第三層k：負責從0數到3（共4次乘法）
       			C[i][j] += A[i][k] * B[k][j];   //每次相乘的結果，都用+=累加進C[i][j]裡     
    	}
	}

  	//格式化輸出結果矩陣 C
  	printf("\n矩陣相乘結果C(2x5)：\n");
 	for (i = 0; i < 2; i++) {	// 外層：準備印出第 i 橫列
   		printf("row%d ->. ", i + 1);	// 印出開頭標題（因為程式從0開始算，所以i+1才會顯示row1、row2）
    	for (j = 0; j < 5; j++) {	//內層：依序印出該列的5個數字（j從0跑到4）
      		printf("%d", C[i][j]);	//印出該格的計算結果
      	
     		//判斷要不要印逗號：總共有5個數字（編號0,1,2,3,4）
      		//只要j小於4（代表還沒印到最後一個數字），就在數字後面補上逗號與空格
     		if (j < 4) 
       			printf(", ");
    	}
    	printf("\n");	//整橫列的5個數字都印完後，換到下一行
 	}
  	return 0; 
}
